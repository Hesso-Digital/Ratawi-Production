# Rebuilds src/scene/terrain/demData.ts. Needs Copernicus GLO-30 tiles
# (s3://copernicus-dem-30m, Copernicus_DSM_COG_10_N{29,30,31}_00_E0{46,47}_00_DEM.tif)
# and ESA WorldCover 2021 v200 tile N30E045 in the working directory.
# pip install numpy scipy tifffile imagecodecs zarr pyproj
import numpy as np, tifffile, zarr, json, base64
from pyproj import Transformer
from scipy.ndimage import gaussian_filter, uniform_filter
inv=Transformer.from_crs(32638,4326,always_xy=True)
CPF_E,CPF_N=702980,3382190
tiles={}
for la in (29,30,31):
  for lo in (46,47):
    tiles[(la,lo)]=tifffile.imread(f'Copernicus_DSM_COG_10_N{la}_00_E0{lo}_00_DEM.tif').astype(np.float32)
def samp(lat,lon):
    out=np.zeros_like(lat)
    for (la,lo),T in tiles.items():
        H,W=T.shape
        m=(lat>=la)&(lat<la+1)&(lon>=lo)&(lon<lo+1)
        r=((la+1-lat[m])*H).astype(int).clip(0,H-1); c=((lon[m]-lo)*W).astype(int).clip(0,W-1)
        out[m]=T[r,c]
    return out
# fine 50 m grid over ±64 km for smoothing, then decimate to 1 km
step=50; half=64000
xs=np.arange(-half,half+1,step); X,Y=np.meshgrid(xs,xs[::-1])
lon,lat=inv.transform(CPF_E+X,CPF_N+Y)
Z=samp(lat,lon); np.save('z50.npy',Z.astype(np.float32))
print('±64km raw min %.1f max %.1f'%(Z.min(),Z.max()))
S=gaussian_filter(Z,12)  # sigma 600 m
idx=np.arange(0,len(xs),20)  # 1 km
G=S[np.ix_(idx,idx)]; gx=xs[idx]
print('grid',G.shape,'min %.1f max %.1f'%(G.min(),G.max()))
iy,ix=np.unravel_index(np.argmax(G),G.shape); print('1km max at E %d N %d'%(gx[ix],gx[::-1][iy] if False else xs[::-1][idx][iy]))
np.save('G1km.npy',G)
# worldcover
st=tifffile.imread('ESA_WorldCover_10m_2021_v200_N30E045_Map.tif',aszarr=True); z=zarr.open(st,mode='r'); z=z if hasattr(z,'dtype') else z['0']
latc=np.clip(lat,30.0001,33); 
rr=((33-latc)*12000).astype(int); cc=((lon-45)*12000).astype(int)
r0,r1,c0,c1=rr.min(),rr.max()+1,cc.min(),cc.max()+1
A=np.asarray(z[r0:r1,c0:c1]); L=A[rr-r0,cc-c0]
L[lat<30.0]=60
np.save('L50.npy',L)
wet=((L==80)|(L==90)).astype(np.float32); green=np.isin(L,[10,20,30,40,95]).astype(np.float32); built=(L==50).astype(np.float32)
W1=uniform_filter(wet,20)[np.ix_(idx,idx)]; V1=uniform_filter(green,20)[np.ix_(idx,idx)]
print('wet cells>0.5',(W1>0.5).sum(),'green>0.3',(V1>0.3).sum())
np.save('W1.npy',W1); np.save('V1.npy',V1)
import numpy as np, base64
G=np.load('G1km.npy'); W=np.load('W1.npy'); V=np.load('V1.npy')
n=G.shape[0]
h=np.round(G*10).astype('<i2')
w=np.round(np.clip(W,0,1)*255).astype(np.uint8); v=np.round(np.clip(V,0,1)*255).astype(np.uint8)
b=lambda a: base64.b64encode(a.tobytes()).decode()
src=f'''/**
 * Real ground around the Ratawi field, generated by scripts/terrain/build_dem.py
 * (kept in the repo for re-runs). Do not edit by hand.
 *
 * Grid: {n}x{n} cells at 1 km spacing, centred on CPF-1 (approx. 30.555 N,
 * 47.116 E, UTM 38N E 702 980 / N 3 382 190), row 0 = north edge (+64 km),
 * column 0 = west edge (-64 km).
 *  - HEIGHT_DM: Copernicus GLO-30 DSM (ESA / AWS open data, 2021 release),
 *    Gaussian-smoothed (sigma 600 m) to drop buildings/noise, int16 decimetres.
 *  - WET / GREEN: ESA WorldCover 2021 v200 10 m land cover, share of each 1 km
 *    cell that is open water or herbaceous wetland (WET) and cropland, grass,
 *    shrub or trees (GREEN), 0-255.
 * Findings: field sits on a low N-S spur at ~30 m (CPF-1 31.6 m); ground falls
 * to 0-5 m toward the Hammar marsh / Euphrates floodplain 12-20 km north, and
 * rises gently south-west onto the Dibdibba gravel plain (40-50 m at 15-20 km,
 * 100-170 m at 50-65 km). Slope is ~1 m per km.
 */
export const DEM_N = {n};
export const DEM_SPACING_M = 1000;
export const DEM_HALF_M = {(n-1)//2*1000};
export const DEM_CPF_M = {G[n//2,n//2]:.1f};
export const HEIGHT_DM_B64 =
  '{b(h)}';
export const WET_B64 =
  '{b(w)}';
export const GREEN_B64 =
  '{b(v)}';
'''
open('src/scene/terrain/demData.ts','w').write(src)
print(len(src), G[n//2,n//2])
